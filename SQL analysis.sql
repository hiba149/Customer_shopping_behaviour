Q5. Do subscribed customers spend more? Compare average spend and total revenue between subscribers and non-subscribers.
select subscription_sta, COUNT (customer_id) as customers, ROUND(AVG(purchase_amount), 2) as avg_spends, sum(purchase_amount) AS Total_revenue  FROM customer_shopping_behavior91
as total_revenue GROUP by subscription_sta
order by Total_revenue desc;

Q6. Which 5 products have the highest percentage of purchases with discounts applied?
select item_purchased, round(100.0 * sum (case when discount_applied = 'Yes' then 1 else 0 END ) / COUNT(*), 2) AS discount_applied
from customer_shopping_behavior91 GROUP by item_purchased order by discount_applied limit 5;

Q7. Segment customers into New, Returning, and Loyal based on their total number of previous purchases, and show the count of each segment.
WITH segmented AS (
    SELECT customer_id,
           CASE
               WHEN previous_purchas <= 1 THEN 'New'
               WHEN previous_purchas <= 10 THEN 'Returning'
               ELSE 'Loyal'
           END AS customer_segment
    FROM customer_shopping_behavior91)
SELECT customer_segment, COUNT(*) AS no_of_customers
FROM segmented
GROUP BY customer_segment;

Q8. What are the top 3 most purchased products within each category?
WITH item_counts AS (
    SELECT category,
           item_purchased,
           COUNT(customer_id) AS total_orders,
           ROW_NUMBER() OVER (PARTITION BY category
                              ORDER BY COUNT(customer_id) DESC) AS item_rank
    FROM customer_shopping_behavior91 GROUP BY category, item_purchased)
SELECT item_rank, category, item_purchased, total_orders FROM item_counts WHERE item_rank <= 3 ORDER BY category, item_rank;

Q9. Are customers who are repeat buyers (more than 5 previous purchases) also likely to subscribe?
SELECT CASE WHEN previous_purchas > 5 THEN 'Repeat buyer (>5)'
            ELSE 'Other (<=5)' END AS buyer_type,
       COUNT(*) AS customers,
       SUM(CASE WHEN subscription_sta = 'Yes' THEN 1 ELSE 0 END) AS subscribed,
       ROUND(100.0 * SUM(CASE WHEN subscription_sta = 'Yes' THEN 1 ELSE 0 END) / COUNT(*), 2) AS subscribed_per
FROM customer_shopping_behavior91 GROUP BY buyer_type;

Q10. What is the revenue contribution of each age group?
SELECT CASE
           WHEN age BETWEEN 18 AND 31 THEN 'Young Adult'
           WHEN age BETWEEN 32 AND 44 THEN 'Adult'
           WHEN age BETWEEN 45 AND 57 THEN 'Teenager'
           ELSE 'Senior'
       END AS age_group,
       SUM(purchase_amount) AS total_revenue,
       ROUND(100.0 * SUM(purchase_amount)
             / SUM(SUM(purchase_amount)) OVER (), 2) AS pct_revenue
FROM customer_shopping_behavior91 GROUP BY age_group ORDER BY total_revenue DESC;








